-- Cadre de gestion des clients, lot A : capacites d'une societe et lien client -> partenaire referent.
--
-- societe_capacites : une societe peut cumuler plusieurs capacites (CLIENT, PARTENAIRE, FOURNISSEUR).
-- Un partenaire est aussi un client (il a des fonctionnalites en plus) : il recoit les deux capacites.
-- liens_clients : au plus un partenaire referent par client ; origine = PARTENAIRE (cree par le partenaire)
-- ou INSCRIPTION (inscription autonome) ; changements_annee_courante est compte pour annee_reference.
-- societes_identites.type n'est plus ecrit par le code : la colonne devient nullable (valeurs historiques conservees).
-- Le script est idempotent (IF NOT EXISTS / ON CONFLICT DO NOTHING).

CREATE TABLE IF NOT EXISTS societe_capacites (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    societe_id BIGINT NOT NULL REFERENCES societes_identites (id),
    capacite   VARCHAR(20) NOT NULL,
    cree_a     TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_societe_capacites UNIQUE (societe_id, capacite),
    CONSTRAINT ck_societe_capacites_capacite CHECK (capacite IN ('CLIENT', 'PARTENAIRE', 'FOURNISSEUR'))
);

CREATE TABLE IF NOT EXISTS liens_clients (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_societe_id          BIGINT NOT NULL REFERENCES societes_identites (id),
    partenaire_societe_id      BIGINT NOT NULL REFERENCES societes_identites (id),
    origine                    VARCHAR(20) NOT NULL,
    depuis                     TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    changements_annee_courante INT NOT NULL DEFAULT 0,
    annee_reference            INT,
    CONSTRAINT uq_liens_clients_client UNIQUE (client_societe_id),
    CONSTRAINT ck_liens_clients_origine CHECK (origine IN ('PARTENAIRE', 'INSCRIPTION'))
);

CREATE INDEX IF NOT EXISTS ix_liens_clients_partenaire ON liens_clients (partenaire_societe_id);

-- Reprise de l'existant : la capacite correspond a l'ancien type...
INSERT INTO societe_capacites (societe_id, capacite)
SELECT id, type FROM societes_identites WHERE type IS NOT NULL
ON CONFLICT (societe_id, capacite) DO NOTHING;

-- ... et un partenaire est aussi un client.
INSERT INTO societe_capacites (societe_id, capacite)
SELECT id, 'CLIENT' FROM societes_identites WHERE type = 'PARTENAIRE'
ON CONFLICT (societe_id, capacite) DO NOTHING;

ALTER TABLE societes_identites ALTER COLUMN type DROP NOT NULL;
