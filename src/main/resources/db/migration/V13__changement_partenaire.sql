-- Cadre de gestion des clients, lot A : demandes de changement de partenaire soumises a validation admin
-- (au-dela d'un changement applique par annee civile). Idempotent.

CREATE TABLE IF NOT EXISTS demandes_changement_partenaire (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_societe_id             BIGINT NOT NULL REFERENCES societes_identites (id),
    nouveau_partenaire_societe_id BIGINT NOT NULL REFERENCES societes_identites (id),
    motif                         TEXT,
    cree_a                        TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    statut                        VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE',
    CONSTRAINT ck_demandes_changement_statut CHECK (statut IN ('EN_ATTENTE', 'ACCEPTEE', 'REFUSEE'))
);

CREATE INDEX IF NOT EXISTS ix_demandes_changement_client ON demandes_changement_partenaire (client_societe_id);
