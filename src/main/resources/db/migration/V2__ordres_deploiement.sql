-- Task 3 (deploiement bleu-vert) : table des ordres de deploiement + colonne de suivi, par
-- LicenceServeur, du dernier ordre deja consomme (voir OrdreDeploiement / DeploiementController).
--
-- Noms de colonnes IMPLICITES (pas de @Column(name=...) dans les entites) : la strategie physique
-- Hibernate effectivement appliquee a ce schema (verifie empiriquement sur licence_serveurs /
-- etat_licence_locale, deja en base) est un simple lower-case SANS insertion d'underscore — PAS
-- CamelCaseToUnderscoresNamingStrategy, malgre la propriete
-- spring.jpa.hibernate.naming.physical-strategy du meme nom (ex. codeEnrolementExpireA -> colonne
-- "codeenrolementexpirea", pas "code_enrolement_expire_a"). Ce script suit donc cette MEME
-- convention (deja en vigueur, pas introduite ici) pour que ddl-auto=validate reussisse.

CREATE TABLE IF NOT EXISTS ordres_deploiement (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version VARCHAR(255),
    creea   TIMESTAMP(6) WITH TIME ZONE
);

ALTER TABLE IF EXISTS licence_serveurs
    ADD COLUMN IF NOT EXISTS dernierordredeploiementconsommeid BIGINT;
