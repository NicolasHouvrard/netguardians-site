-- Inscription d'une societe, etape 1 : registre unique des identites de societes.
--
-- Une ligne par societe de la plateforme, tous types confondus (client, partenaire, fournisseur) : un meme
-- SIREN ou une meme TVA ne peut y figurer qu'une fois. Les societes etrangeres n'ont pas de SIREN
-- (colonne nulle) et ne sont identifiees que par leur TVA : l'index sur le SIREN ignore les valeurs nulles.
-- proprietaire_tenant_id : tenant du partenaire proprietaire ; NULL = le Maitre. fiche_type / fiche_id :
-- lien vers la fiche de la societe dans sa table d'origine (renseigne par les etapes suivantes).

CREATE TABLE IF NOT EXISTS societes_identites (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siren                  VARCHAR(9),
    tva                    VARCHAR(20) NOT NULL,
    type                   VARCHAR(20) NOT NULL,
    proprietaire_tenant_id BIGINT,
    fiche_type             VARCHAR(30),
    fiche_id               BIGINT,
    cree_a                 TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_societes_identites_siren ON societes_identites (siren) WHERE siren IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_societes_identites_tva ON societes_identites (tva);
