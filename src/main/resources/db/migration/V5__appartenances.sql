-- Inscription d'une societe, etape 2 : appartenances multi-societes.
--
-- Une personne (un utilisateur) peut appartenir a plusieurs societes. Chaque appartenance porte le tenant
-- de la societe, la fiche client de la personne dans cette societe (customer_id, nul si elle n'en a pas)
-- et ses roles dans cette societe.

CREATE TABLE IF NOT EXISTS appartenances (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    tenant_id   BIGINT NOT NULL REFERENCES tenants (id),
    customer_id BIGINT,
    cree_a      TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now()
);

-- Un customer_id nul compte comme une valeur : sans le COALESCE, deux lignes sans fiche passeraient.
CREATE UNIQUE INDEX IF NOT EXISTS uq_appartenances_user_tenant_fiche
    ON appartenances (user_id, tenant_id, (COALESCE(customer_id, 0)));

CREATE INDEX IF NOT EXISTS idx_appartenances_user ON appartenances (user_id);

CREATE TABLE IF NOT EXISTS appartenances_roles (
    appartenance_id BIGINT NOT NULL REFERENCES appartenances (id) ON DELETE CASCADE,
    role_id         BIGINT NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    PRIMARY KEY (appartenance_id, role_id)
);

-- Reprise de l'existant (idempotente) : une appartenance par utilisateur ayant un tenant.
INSERT INTO appartenances (user_id, tenant_id, customer_id)
SELECT u.id, u.tenant_id, u.customer_id
FROM users u
WHERE u.tenant_id IS NOT NULL
ON CONFLICT DO NOTHING;

INSERT INTO appartenances_roles (appartenance_id, role_id)
SELECT a.id, ur.role_id
FROM appartenances a
JOIN users u ON u.id = a.user_id
    AND u.tenant_id = a.tenant_id
    AND COALESCE(u.customer_id, 0) = COALESCE(a.customer_id, 0)
JOIN users_roles ur ON ur.user_id = u.id
ON CONFLICT DO NOTHING;
